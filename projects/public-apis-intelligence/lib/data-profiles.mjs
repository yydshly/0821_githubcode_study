const splitDescriptionObjects = (description) => description
  .replace(/^(查询|获取|发现|读取|同步|提供|访问|判断|检查|搜索|生成|创建|管理|计算|分析|估算|转换|上传|下载|检索|跟踪|发现)/, "")
  .split(/[、，]|和|与/)
  .map((item) => item.trim())
  .filter((item) => item.length >= 2)
  .slice(0, 8);

export function enrichScenarioDefinition(definition) {
  const profile = CATEGORY_DATA_PROFILES[definition.category];
  const rule = SCENARIO_FIELD_RULES.find(([pattern]) => pattern.test(`${definition.id} ${definition.name}`));
  const fields = rule ? split(rule[1]) : profile?.fields ?? [];
  const dataObjects = definition.general ? profile?.objects ?? [] : splitDescriptionObjects(definition.description);
  return {
    ...definition,
    dataObjects,
    searchTerms: [...new Set([...dataObjects, ...(profile?.objects ?? [])])],
    typicalInputs: profile?.inputs ?? [],
    exampleFields: fields,
    question: definition.general
      ? profile?.question ?? "这类数据能解决什么问题？"
      : `在“${definition.products.split("、").slice(0, 2).join("、")}”中，如何获得${definition.name}所需的数据？`
  };
}

export function buildDataCatalog(entries, scenarios) {
  const groups = [...new Set(entries.map((entry) => entry.group))].map((group) => {
    const groupEntries = entries.filter((entry) => entry.group === group);
    const categories = [...new Set(groupEntries.map((entry) => entry.category))].map((category) => {
      const profile = CATEGORY_DATA_PROFILES[category];
      const categoryEntries = groupEntries.filter((entry) => entry.category === category);
      const categoryScenarios = scenarios.filter((scenario) => scenario.category === category && !scenario.general);
      return {
        category,
        label: profile?.label ?? category,
        apiCount: categoryEntries.length,
        scenarioCount: categoryScenarios.length,
        objects: profile?.objects ?? [],
        inputs: profile?.inputs ?? [],
        fields: profile?.fields ?? [],
        question: profile?.question ?? ""
      };
    });
    const representativeObjects = categories.flatMap((category) => category.objects.slice(0, 2));
    const allObjects = categories.flatMap((category) => category.objects);
    return {
      group,
      apiCount: groupEntries.length,
      categoryCount: categories.length,
      scenarioCount: scenarios.filter((scenario) => scenario.group === group && !scenario.general).length,
      objects: [...new Set([...representativeObjects, ...allObjects])],
      categories
    };
  });
  return groups.sort((a, b) => b.apiCount - a.apiCount || a.group.localeCompare(b.group, "zh-CN"));
}
